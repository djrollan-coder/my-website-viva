/* ============================================================
   Механизм переключения языков
   ============================================================ */

var currentLang = 'es';

function setLanguage(lang) {
    if (!translations[lang]) return;
    currentLang = lang;
    window.currentLang = lang;

    document.querySelectorAll('[data-translate]').forEach(function (el) {
        var key = el.getAttribute('data-translate');
        if (translations[lang][key]) {
            el.textContent = translations[lang][key];
        }
    });

    document.querySelectorAll('[data-translate-placeholder]').forEach(function (el) {
        var key = el.getAttribute('data-translate-placeholder');
        if (translations[lang][key]) {
            el.setAttribute('placeholder', translations[lang][key]);
        }
    });

    document.documentElement.lang = lang;

    document.querySelectorAll('.flag-btn').forEach(function (btn) {
        btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
    });

    try { localStorage.setItem('viadomotica_lang', lang); } catch (e) {}
}

/* translations.js подключён с defer, поэтому DOM уже разобран.
   Инициализируем язык сразу, до DOMContentLoaded и первого стабильного рендера. */
(function initLanguageImmediately() {

    document.querySelectorAll('.flag-btn').forEach(function (btn) {
        btn.addEventListener('click', function () {
            setLanguage(this.getAttribute('data-lang'));
        });
    });

    var urlLang = new URLSearchParams(window.location.search).get('lang');
    var savedLang = null;
    try { savedLang = localStorage.getItem('viadomotica_lang'); } catch (e) {}

    if (urlLang && translations[urlLang]) {
        setLanguage(urlLang);
    } else if (savedLang && translations[savedLang]) {
        setLanguage(savedLang);
    } else {
        setLanguage('es');
    }
})();
